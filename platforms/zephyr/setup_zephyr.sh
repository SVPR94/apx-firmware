# pinned Arm GNU Toolchain from platforms/stm32h7/setup_toolchain.sh
# (Zephyr's "gnuarmemb" toolchain variant), so no Zephyr SDK is needed.
#
# Idempotent: re-running updates the workspace to the pinned version.
#
# Usage:
#   platforms/zephyr/setup_zephyr.sh
#   source platforms/zephyr/workspace/env.sh     # then build, see README.md

set -euo pipefail

# Pinned: bump deliberately and re-verify the board build.
APX_ZEPHYR_VERSION="v4.4.2"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
WS="${APX_ZEPHYR_WORKSPACE:-${SCRIPT_DIR}/workspace}"
VENV="${WS}/.venv"
ENV_FILE="${WS}/env.sh"

log() { echo -e "\033[1;34m[setup_zephyr]\033[0m $*"; }
die() { echo -e "\033[1;31m[setup_zephyr] ERROR:\033[0m $*" >&2; exit 1; }

command -v python3 >/dev/null || die "python3 not found"
command -v cmake >/dev/null || die "cmake not found (run tools/setup_ubuntu_env.sh)"
command -v ninja >/dev/null || die "ninja not found (run tools/setup_ubuntu_env.sh)"

# ARM compiler (same pinned toolchain as the bare-metal build)
"${REPO_ROOT}/platforms/stm32h7/setup_toolchain.sh" >/dev/null
TC_ENV="${REPO_ROOT}/platforms/stm32h7/toolchain/env.sh"
[[ -f "${TC_ENV}" ]] || die "ARM toolchain env not found at ${TC_ENV}"
# shellcheck disable=SC1090
. "${TC_ENV}"
GCC_BIN="$(command -v arm-none-eabi-gcc)" || die "arm-none-eabi-gcc not on PATH after toolchain setup"
TC_ROOT="$(dirname "$(dirname "${GCC_BIN}")")"

mkdir -p "${WS}"
# Zephyr ${APX_ZEPHYR_VERSION} needs Python >= 3.12 (Ubuntu 22.04 ships 3.10).
# Use the system python3 when new enough, else a uv-managed 3.12 for this
# workspace only (no sudo, system Python untouched).
venv_ok() {
    [[ -x "${VENV}/bin/python" ]] &&
        "${VENV}/bin/python" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 12) else 1)'
}
if ! venv_ok; then
    rm -rf "${VENV}"
    if python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 12) else 1)'; then
        log "Creating Python venv ${VENV}"
        python3 -m venv "${VENV}"
    else
        if ! command -v uv >/dev/null; then
            log "Installing uv (user site) to provide Python 3.12..."
            python3 -m pip install --user --quiet uv 2>/dev/null \
                || python3 -m pip install --user --quiet --break-system-packages uv
            export PATH="${HOME}/.local/bin:${PATH}"
        fi
        log "Creating Python 3.12 venv ${VENV} with uv"
        uv venv --quiet --seed --python 3.12 "${VENV}"
    fi
fi
# shellcheck disable=SC1091
. "${VENV}/bin/activate"
python -m pip install --quiet --upgrade pip west

if [[ ! -d "${WS}/.west" ]]; then
    log "Initialising west workspace at ${WS} (Zephyr ${APX_ZEPHYR_VERSION})"
    west init -m https://github.com/zephyrproject-rtos/zephyr --mr "${APX_ZEPHYR_VERSION}" "${WS}"
fi
cd "${WS}"
git -C zephyr fetch --quiet --depth 1 origin "refs/tags/${APX_ZEPHYR_VERSION}:refs/tags/${APX_ZEPHYR_VERSION}" || true
git -C zephyr checkout --quiet "${APX_ZEPHYR_VERSION}"

# Only the modules the STM32H7 firmware uses.
west config manifest.project-filter -- '-.*,+cmsis,+cmsis_6,+hal_stm32'
log "Fetching Zephyr modules (STM32 HAL, CMSIS)..."
west update --narrow --fetch-opt=--depth=1

log "Installing Zephyr Python requirements into the venv..."
python -m pip install --quiet -r zephyr/scripts/requirements-base.txt

cat > "${ENV_FILE}" <<EOF
# Generated by platforms/zephyr/setup_zephyr.sh - source before building APX for hardware.
. "${VENV}/bin/activate"
export ZEPHYR_BASE="${WS}/zephyr"
export ZEPHYR_TOOLCHAIN_VARIANT=gnuarmemb
export GNUARMEMB_TOOLCHAIN_PATH="${TC_ROOT}"
EOF

log "Done. Zephyr ${APX_ZEPHYR_VERSION} in ${WS}"
log "Build: source ${ENV_FILE} && west build -b cube_orange_plus/stm32h757xx/m7 platforms/zephyr/app"
