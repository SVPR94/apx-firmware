# expected version is already extracted, it's reused without re-downloading.
#
# Usage:
#   platforms/stm32h7/setup_toolchain.sh              # install + print env
#   source <(platforms/stm32h7/setup_toolchain.sh -e)  # install + export PATH into current shell
#
# After running, either `source` its env.sh as shown above, or add the
# printed bin/ directory to PATH yourself, then:
#   arm-none-eabi-gcc --version

set -euo pipefail

# Pinned, not "always latest": a reproducible build needs a known-good
# compiler version, not whatever happens to be newest on the day someone
# runs this script. Bump this deliberately (and re-verify the STM32H7
# build) rather than tracking Arm's release stream automatically.
APX_ARM_TOOLCHAIN_VERSION="15.2.rel1"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INSTALL_ROOT="${APX_TOOLCHAIN_DIR:-${SCRIPT_DIR}/toolchain}"
VERSION_DIR="${INSTALL_ROOT}/${APX_ARM_TOOLCHAIN_VERSION}"
ENV_FILE="${INSTALL_ROOT}/env.sh"

print_env_only=0
if [[ "${1:-}" == "-e" || "${1:-}" == "--env" ]]; then
    print_env_only=1
fi

detect_host_triplet() {
    local os arch
    os="$(uname -s)"
    arch="$(uname -m)"
    case "${os}-${arch}" in
        Linux-x86_64)   echo "x86_64-arm-none-eabi" ;;
        Linux-aarch64)  echo "aarch64-arm-none-eabi" ;;
        Darwin-arm64)   echo "darwin-arm64-arm-none-eabi" ;;
        Darwin-x86_64)  echo "darwin-x86_64-arm-none-eabi" ;;
        *)
            echo "[setup_toolchain] Unsupported host: ${os}-${arch}." >&2
            echo "[setup_toolchain] See https://developer.arm.com/downloads/-/arm-gnu-toolchain-downloads" >&2
            echo "[setup_toolchain] and adjust APX_ARM_TOOLCHAIN_VERSION/this script's platform map by hand." >&2
            exit 1
            ;;
    esac
}

find_compiler_dir() {
    # The archive's top-level directory name varies slightly by platform
    # (e.g. "arm-gnu-toolchain-15.2.rel1-x86_64-arm-none-eabi") - find it
    # rather than hardcoding, and print the directory that actually
    # contains bin/arm-none-eabi-gcc.
    find "${VERSION_DIR}" -maxdepth 2 -type f -name 'arm-none-eabi-gcc' -path '*/bin/*' 2>/dev/null \
        | head -n1 | xargs -r dirname | xargs -r dirname
}

already_installed_dir="$(find_compiler_dir || true)"

if [[ -n "${already_installed_dir}" ]]; then
    echo "[setup_toolchain] Arm GNU Toolchain ${APX_ARM_TOOLCHAIN_VERSION} already installed at:" >&2
    echo "  ${already_installed_dir}" >&2
else
    host_triplet="$(detect_host_triplet)"
    archive_name="arm-gnu-toolchain-${APX_ARM_TOOLCHAIN_VERSION}-${host_triplet}.tar.xz"
    url="https://developer.arm.com/-/media/Files/downloads/gnu/${APX_ARM_TOOLCHAIN_VERSION}/binrel/${archive_name}"

    echo "[setup_toolchain] Installing Arm GNU Toolchain ${APX_ARM_TOOLCHAIN_VERSION} (${host_triplet})" >&2
    echo "[setup_toolchain] Source: ${url}" >&2

    mkdir -p "${VERSION_DIR}"
    tmp_archive="$(mktemp -t "arm-gnu-toolchain-XXXXXX.tar.xz")"
    trap 'rm -f "${tmp_archive}"' EXIT

    if ! curl -fL --retry 3 --retry-delay 2 -o "${tmp_archive}" "${url}"; then
        echo "[setup_toolchain] Download failed. Check network access, or install the" >&2
        echo "  distro package instead (older, but works offline once cached):" >&2
        echo "    sudo apt install gcc-arm-none-eabi" >&2
        exit 1
    fi

    echo "[setup_toolchain] Extracting..." >&2
    tar -xJf "${tmp_archive}" -C "${VERSION_DIR}" --strip-components=1
    rm -f "${tmp_archive}"
    trap - EXIT

    already_installed_dir="$(find_compiler_dir || true)"
    if [[ -z "${already_installed_dir}" ]]; then
        echo "[setup_toolchain] Extracted archive but couldn't find bin/arm-none-eabi-gcc under ${VERSION_DIR} - archive layout may have changed." >&2
        exit 1
    fi
fi

bin_dir="${already_installed_dir}/bin"

if ! "${bin_dir}/arm-none-eabi-gcc" --version >/dev/null 2>&1; then
    echo "[setup_toolchain] ${bin_dir}/arm-none-eabi-gcc exists but failed to run - install looks broken." >&2
    exit 1
fi

mkdir -p "${INSTALL_ROOT}"
cat > "${ENV_FILE}" <<EOF
# Generated by setup_toolchain.sh - source this to put arm-none-eabi-* on PATH.
export PATH="${bin_dir}:\${PATH}"
export APX_ARM_TOOLCHAIN_BIN="${bin_dir}"
EOF

if [[ "${print_env_only}" -eq 1 ]]; then
    cat "${ENV_FILE}"
else
    echo "[setup_toolchain] Ready:" >&2
    "${bin_dir}/arm-none-eabi-gcc" --version | head -n1 >&2
    echo >&2
    echo "[setup_toolchain] Add it to your shell with:" >&2
    echo "  source ${ENV_FILE}" >&2
fi
